import sys
M = (1 << 64) - 1
G = 0x9E3779B97F4A7C15
def mix(z):
    z &= M
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & M
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & M
    return z ^ (z >> 31)
def splitmix(seed, n):
    s = seed & M
    out = []
    for _ in range(n):
        s = (s + G) & M
        out.append(mix(s))
    return out
def fnv(s):
    h = 0xcbf29ce484222325
    for b in s.encode('utf-8'):
        h ^= b
        h = (h * 0x100000001b3) & M
    return h
SEED = 0x243F6A8885A308D3
def hash_of(*parts):
    h = SEED
    for p in parts:
        h = mix(((h ^ (p & M)) + G) & M)
    return h
